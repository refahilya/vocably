import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:cloud_firestore/cloud_firestore.dart' show FieldPath;
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:vocably/models/research_attempt.dart';
import 'package:vocably/models/research_instrument.dart';
import 'package:vocably/models/research_participant.dart';
import 'package:vocably/utils/research_attempt_planner.dart';

/// Keeps the app's research writes and the real `firestore.rules` in step.
///
/// This test builds the exact payloads the app sends (create, one answer
/// per item covering every display position including "tidak tahu", and
/// completion) through the same builders `ResearchAssessmentService` uses,
/// and compares them with the checked-in fixture
/// `tools/research/test/fixtures/client_payloads.json`. The emulator suite
/// (`tools/research/test/rules/clientPayloads.test.js`) replays that same
/// fixture against the real rules. A change to either side that breaks the
/// contract therefore fails a test.
///
/// The answers are fabricated (position = item index mod 5 + 1); nothing is
/// derived from the answer key. Regenerate after an intended change with
/// `VOCABLY_UPDATE_FIXTURES=1 flutter test test/research_client_payloads_test.dart`.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const fixturePath = 'tools/research/test/fixtures/client_payloads.json';
  const ts = '__serverTimestamp__';
  const uid = 'dartClientStudent';

  /// JSON form of a payload; a [FieldPath] key becomes
  /// `fieldPath:<segment>/<segment>` (item IDs never contain `/`).
  Object? jsonable(Object? value) => switch (value) {
    Map() => {
      for (final e in value.entries)
        (e.key is FieldPath
            ? 'fieldPath:${(e.key as FieldPath).components.join('/')}'
            : e.key as String): jsonable(
          e.value,
        ),
    },
    List() => [for (final v in value) jsonable(v)],
    _ => value,
  };

  Future<Map<String, Object?>> buildFixture() async {
    final instrument = ResearchInstrument.fromJson(
      jsonDecode(
        await rootBundle.loadString('assets/research/instrument_v1.json'),
      ),
      expectedVersion: 'v1',
    );
    final assignment = const ResearchParticipantAssignment(
      band: 'B1',
      instrumentVersion: 'v1',
    );

    Map<String, Object?> attempt(ResearchStage stage, int seed) {
      final plan = planResearchAttempt(
        instrument: instrument,
        assignment: assignment,
        random: Random(seed),
      );
      return {
        'attemptId': ResearchAttemptRecord.idFor(uid, stage, 1),
        'create': jsonable(
          ResearchAttemptRecord.newAttemptData(
            studentId: uid,
            stage: stage,
            attemptNumber: 1,
            plan: plan,
            serverTimestamp: ts,
          ),
        ),
        'answers': [
          for (var i = 0; i < plan.items.length; i++)
            {
              'itemId': plan.items[i].itemId,
              'update': jsonable(
                ResearchAttemptRecord.answerUpdateData(
                  itemId: plan.items[i].itemId,
                  response: ResearchResponse.forPlannedItem(
                    plan.items[i],
                    plan.items[i].displayOptions[i % 5].id,
                  ),
                  serverTimestamp: ts,
                ),
              ),
            },
        ],
        'complete': jsonable(ResearchAttemptRecord.completionData(ts)),
      };
    }

    return {
      'description':
          'Generated by test/research_client_payloads_test.dart from the '
          'app\'s payload builders. Fabricated answers; no answer-key data.',
      'serverTimestampMarker': ts,
      'uid': uid,
      'band': assignment.band,
      'instrumentVersion': assignment.instrumentVersion,
      'preTest': attempt(ResearchStage.preTest, 2024),
      'postTest': attempt(ResearchStage.postTest, 2025),
    };
  }

  test('the app payloads match the fixture replayed against the rules', () async {
    final encoded =
        '${const JsonEncoder.withIndent('  ').convert(await buildFixture())}\n';
    final file = File(fixturePath);
    if (Platform.environment['VOCABLY_UPDATE_FIXTURES'] == '1') {
      file.writeAsStringSync(encoded);
    }
    expect(
      file.existsSync(),
      isTrue,
      reason: 'run with VOCABLY_UPDATE_FIXTURES=1 to create $fixturePath',
    );
    expect(file.readAsStringSync().replaceAll('\r\n', '\n'), encoded);
  });
}
