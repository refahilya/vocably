import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:cloud_firestore/cloud_firestore.dart' show FieldPath;
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:vocably/models/placement_attempt.dart';
import 'package:vocably/models/placement_instrument.dart';

/// Keeps the app's Placement Test writes and the real `firestore.rules` in
/// step: builds the exact payloads `PlacementService` sends (create with a
/// per-band shuffle, answers incl. a changed answer and E, the lifecycle
/// counter, submit, and the six scoring proposals with their `users` and
/// participant writes) and compares them with the checked-in fixture
/// `tools/research/test/fixtures/placement_client_payloads.json`, which the
/// emulator suite (`tools/research/test/rules/placementClientFlow.test.js`)
/// replays against the real rules.
///
/// Answers are fabricated (letter by display position); nothing is derived
/// from the answer key. Regenerate after an intended change with
/// `VOCABLY_UPDATE_FIXTURES=1 flutter test test/placement_client_payloads_test.dart`.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const fixturePath = 'tools/research/test/fixtures/placement_client_payloads.json';
  const ts = '__serverTimestamp__';
  const uid = 'dartPlacementStudent';

  Object? jsonable(Object? value) => switch (value) {
    Map() => {
      for (final e in value.entries)
        (e.key is FieldPath ? 'fieldPath:${(e.key as FieldPath).components.join('/')}' : e.key as String):
            jsonable(e.value),
    },
    List() => [for (final v in value) jsonable(v)],
    _ => value,
  };

  Future<Map<String, Object?>> buildFixture() async {
    final instrument = PlacementInstrument.fromJson(jsonDecode(await rootBundle.loadString(kPlacementBankAsset)));
    Map<String, Object?> attempt(PlacementContext context, int seed) {
      final id = PlacementAttemptRecord.idFor(uid, context, 1);
      final order = PlacementAttemptRecord.buildItemOrder(instrument, Random(seed));
      return {
        'attemptId': id,
        'create': jsonable(PlacementAttemptRecord.newAttemptData(
          studentId: uid,
          context: context,
          attemptNumber: 1,
          itemOrder: order,
          serverTimestamp: ts,
        )),
        'answers': [
          for (var i = 0; i < order.length; i++)
            {
              'itemId': order[i],
              'update': jsonable(PlacementAttemptRecord.answerUpdateData(
                itemId: order[i],
                answer: kPlacementAnswerIds[i % 5],
                serverTimestamp: ts,
              )),
            },
        ],
        'changeFirstAnswer': jsonable(PlacementAttemptRecord.answerUpdateData(itemId: order[0], answer: 'E', serverTimestamp: ts)),
        'tabSwitch': jsonable(PlacementAttemptRecord.tabSwitchData(1, ts)),
        'submit': jsonable(PlacementAttemptRecord.submitData(ts)),
        'scoreProposals': [
          for (final candidate in PlacementResult.candidates)
            {
              'attempt': jsonable(PlacementAttemptRecord.scoreData(candidate, ts)),
              'user': jsonable(PlacementAttemptRecord.userResultData(candidate, id)),
              if (context == PlacementContext.research)
                'participant': jsonable(PlacementAttemptRecord.participantBandData(candidate, id, ts)),
            },
        ],
      };
    }

    return {
      'description':
          'Generated by test/placement_client_payloads_test.dart from the app\'s payload builders. '
          'Fabricated answers; no answer-key data.',
      'serverTimestampMarker': ts,
      'uid': uid,
      'instrumentVersion': kPlacementInstrumentVersion,
      'research': attempt(PlacementContext.research, 2026),
      'learning': attempt(PlacementContext.learning, 2027),
    };
  }

  test('the app placement payloads match the fixture replayed against the rules', () async {
    final encoded = '${const JsonEncoder.withIndent('  ').convert(await buildFixture())}\n';
    final file = File(fixturePath);
    if (Platform.environment['VOCABLY_UPDATE_FIXTURES'] == '1') file.writeAsStringSync(encoded);
    expect(file.existsSync(), isTrue, reason: 'run with VOCABLY_UPDATE_FIXTURES=1 to create $fixturePath');
    expect(file.readAsStringSync().replaceAll('\r\n', '\n'), encoded);
  });
}
